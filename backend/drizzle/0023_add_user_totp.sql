-- Codici di recupero: senza una via d'uscita la 2FA sarebbe soprattutto un nuovo modo di
-- restare chiusi fuori. In tabella solo lo sha256, come per i token di sessione: sono già
-- casuali, quindi non c'è nulla da indovinare a forza bruta e un archivio di backup non
-- deve consegnare codici riutilizzabili.
CREATE TABLE "user_recovery_code" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "user_recovery_code_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"user_id" integer NOT NULL,
	"code_hash" varchar(64) NOT NULL,
	"used_at" timestamp,
	"created_at" timestamp DEFAULT now() NOT NULL
);
