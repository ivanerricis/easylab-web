-- Secondo fattore di autenticazione (TOTP), opzionale per utente.
--
-- Da quando l'app risponde sul dominio pubblico, il form di login è raggiungibile da
-- chiunque e fra un estraneo e i dati dei clienti c'è solo una password: il limitatore per
-- IP ferma la forza bruta, non la password già nota per phishing o riuso.
--
-- `totp_confirmed_at` è il vero interruttore: la 2FA è attiva solo se valorizzato. Un
-- segreto generato e mai confermato (QR mostrato e finestra chiusa) resta lì innocuo e
-- viene sovrascritto al tentativo successivo, senza bisogno di ripulirlo.
--
-- `totp_last_step` ricorda l'ultimo passo temporale accettato: un codice vale trenta
-- secondi, e senza questa memoria chi lo intercetta potrebbe rigiocarlo finché è vivo.
