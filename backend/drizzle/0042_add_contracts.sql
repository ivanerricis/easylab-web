-- Contratti fra i clienti del laboratorio e i fornitori. Il modello è una generalizzazione con
-- due specializzazioni disgiunte e totali: `contract` porta i dati comuni, `assistance` quelli
-- dei contratti di assistenza (pacchetti di ore al mese); il noleggio non ha ancora dati propri,
-- quindi non ha tabella.
--
-- La disgiunzione la fa il database: `assistance.contract_type` vale sempre 'assistance' e la
-- chiave esterna composta (contract_id, contract_type) -> contract(id, type) rende impossibile
-- agganciare una riga di assistenza a un contratto di noleggio. La totalità (ogni contratto di
-- assistenza ha la sua riga) non si esprime in SQL senza trigger differiti: la garantisce la
-- rotta, che scrive contratto e riga nella stessa transazione.
--
-- Il CHECK dei pacchetti ripete a mano `assistancePackageHours` di `schema.ts`: usa
-- `IS NOT NULL` esplicito perché con ore NULL un `IN` vale NULL, e un CHECK che vale NULL passa.
--
-- `intervention.contract_id` è facoltativo; la chiave composta (customer_id, contract_id) ->
-- contract(customer_id, id) garantisce che il contratto sia dello stesso cliente
-- dell'intervento (MATCH SIMPLE: con contract_id NULL non vincola niente, e le righe esistenti
-- restano valide). Infine il tipo `lab` (intervento in laboratorio) entra nel CHECK dei tipi.
